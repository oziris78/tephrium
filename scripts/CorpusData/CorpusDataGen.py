import os


CSV_PATH = os.path.join(os.path.dirname(__file__), 'words_pos.csv')
OUT_PATH = os.path.join(os.path.dirname(__file__), 'CorpusData.java')


sp = lambda i: " " * i


def len_st_with(words: list[str], initial: str) -> int:
    i = 0
    for word in words:
        if word.startswith(initial):
            i += 1
    return i


def valid_word_tuple(word_tuple) -> bool:
    word = word_tuple[0]
    tag = word_tuple[1]

    if tag in ['VBN', 'VBG', 'VBD', 'NNS']: return False
    if len(word) < 4: return False
    if len(word) > 7: return False

    for c in word:
        if c not in 'abcdefghijklmnopqrstuvwxyz':
            return False
    
    last_c = ''
    for c in word:
        if (c == last_c) and (c in "aeiou"):
            return False
        last_c = c

    vowel_count = 0
    for c in word:
        if c in "aeiou":
            vowel_count += 1
            if vowel_count >= 3:
                return False
        else:
            vowel_count = 0

    return True


def get_sorted_words() -> list[str]:
    # Read the CSV file's lines
    with open(CSV_PATH, "r", encoding="utf-8") as csv_file:
        lines = csv_file.read().split('\n')
        lines = lines[1:]
        lines = [line for line in lines if line.strip() != ""]

    # Parse the CSV file
    words = [(line.split(',')[1], line.split(',')[2]) for line in lines]
    words = [wtuple[0] for wtuple in words if valid_word_tuple(wtuple)]

    words.sort()
    return words


def main() -> None:
    words = get_sorted_words()

    # Generate CorpusData.java
    with open(OUT_PATH, "w", encoding="utf-8") as file:
        # Write class definition with its javadoc
        file.write("/**\n")
        file.write('* This package-private class contains an array of random English words that were obtained\n')
        file.write('* from a public domain (CC0) English corpus dataset that is available\n')
        file.write('* <a href="https://www.kaggle.com/datasets/ruchi798/part-of-speech-tagging">here</a><br>\n')
        file.write(f'* <b>NOTE: This class was generated by scripts/{os.path.basename(__file__)}.</b>\n')
        file.write('*/\n')
        file.write("class CorpusData {\n\n")

        # Write buckets into ws array
        file.write(sp(4) + "static final String[][] ws = new String[][] {\n")
        file.write(sp(8) + "CP_A.W, CP_B.W, CP_C.W, CP_D.W, CP_E.W, CP_F.W, CP_G.W, CP_H.W, CP_I.W,\n")
        file.write(sp(8) + "CP_J.W, CP_K.W, CP_L.W, CP_M.W, CP_N.W, CP_O.W, CP_P.W, CP_Q.W, CP_R.W,\n")
        file.write(sp(8) + "CP_S.W, CP_T.W, CP_U.W, CP_V.W, CP_W.W, CP_X.W, CP_Y.W, CP_Z.W\n")
        file.write(sp(4) + "};\n\n")

        # write lengths into ls array
        file.write(sp(4) + "static final int[] ls = new int[] {\n")

        file.write(sp(8))
        for li, letter in enumerate("abcdefghijklmnopqrstuvwxyz"):
            file.write(f"{len_st_with(words, letter)}")
            if li != 25:
                file.write(", ")
            if li == 13:
                file.write(f"\n{sp(8)}")
        file.write(f"\n{sp(4)}}};\n\n")

        file.write(sp(4) + f"static final int TOTAL_WORD_COUNT = {len(words)};\n\n")

        # Write static classes
        for letter in 'abcdefghijklmnopqrstuvwxyz':
            class_name = f"CP_{letter.upper()}"
            words_for_letter = [word for word in words if word.startswith(letter)]
            file.write(sp(4) + f"private static class {class_name} {{\n")
            file.write(sp(8) + f"static final String[] W = new String[] {{")
            if words_for_letter:
                file.write(f'"{words_for_letter[0]}"')
                for word in words_for_letter[1:]:
                    file.write(f', "{word}"')
            file.write("};\n")
            file.write(sp(4) + "}\n\n")

        file.write('\n}\n')


if __name__ == '__main__':
    main()

